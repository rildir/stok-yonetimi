import { Entity, PrimaryColumn, Column, CreateDateColumn, Index, ManyToOne, JoinColumn } from 'typeorm';
import { CompanyEntity } from './company.entity';
import { ProductEntity } from './product.entity';
import { StockMovementType } from './enums';
import { WarehouseEntity } from './warehouse.entity';
import { qtyColumn } from '../utils/quantity-transformer';

/**
 * Stock ledger row. Append-only (TTK 65/3, VUK 217): UPDATE / DELETE are rejected by
 * DB triggers, corrections are REVERSAL rows. Each company's rows form a SHA-256
 * chain (sequenceNo, prevHash, hash) written only by WarehouseStockService.
 * Company / product / warehouse references are RESTRICT, so deleting them never
 * removes movements; product / warehouse names are snapshotted.
 */
@Entity('stock_movements')
@Index('IDX_stock_movements_companyId', ['companyId'])
@Index('UQ_stock_movements_company_seq', ['companyId', 'sequenceNo'], { unique: true })
@Index('IDX_stock_movements_company_txdate', ['companyId', 'transactionDate'])
export class StockMovementEntity {
  /** Generated by the application (it is part of the hash). */
  @PrimaryColumn({ type: 'varchar', length: 36 })
  id: string;

  @Column({ type: 'varchar', length: 36 })
  companyId: string;

  @ManyToOne(() => CompanyEntity, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'companyId', foreignKeyConstraintName: 'FK_stock_movements_company' })
  company?: CompanyEntity;

  @Index()
  @Column()
  productId: string;

  @ManyToOne(() => ProductEntity, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'productId', foreignKeyConstraintName: 'FK_stock_movements_product' })
  product?: ProductEntity;

  @Column()
  productName: string;

  /** Snapshot of the SKU at the time of the movement */
  @Column({ type: 'varchar', length: 255, nullable: true })
  productSku?: string | null;

  @Index()
  @Column({ type: 'varchar' })
  type: StockMovementType | string;

  /** Why stock changed (SALE, PURCHASE, LOSS_ZAYI, COUNT_SURPLUS, ...); see MOVEMENT_REASONS */
  @Index('IDX_stock_movements_reasonCode')
  @Column({ type: 'varchar', length: 30 })
  reasonCode: string;

  /** Signed change in the product's base unit */
  @Column(qtyColumn())
  quantity: number;

  @Column(qtyColumn())
  previousQuantity: number;

  @Column(qtyColumn())
  newQuantity: number;

  /** Base unit code snapshot */
  @Column({ type: 'varchar', length: 20, nullable: true })
  unitCode?: string | null;

  @Index('IDX_stock_movements_warehouseId')
  @Column({ type: 'varchar', length: 36, nullable: true })
  warehouseId?: string | null;

  @ManyToOne(() => WarehouseEntity, { nullable: true, onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'warehouseId', foreignKeyConstraintName: 'FK_stock_movements_warehouse' })
  warehouse?: WarehouseEntity | null;

  /** Warehouse name snapshot */
  @Column({ type: 'varchar', length: 255, nullable: true })
  warehouseName?: string | null;

  /** Lot affected (lot-tracked products); lotNumber is a snapshot. */
  @Index('IDX_stock_movements_lotId')
  @Column({ type: 'varchar', length: 36, nullable: true })
  lotId?: string | null;

  @Column({ type: 'varchar', length: 64, nullable: true })
  lotNumber?: string | null;

  /** Serial numbers moved (serial-tracked products). */
  @Column({ type: 'simple-json', nullable: true })
  serials?: string[] | null;

  /** When the goods actually moved (UTC, whole seconds); periods and reports use this, not createdAt. */
  @Column({ type: 'datetime' })
  transactionDate: Date;

  /** ORDER | PURCHASE_ORDER | INVOICE | DESPATCH | GOODS_RECEIPT | STOCK_COUNT | TRANSFER | DESTRUCTION_REPORT | ... */
  @Column({ type: 'varchar', length: 30, nullable: true })
  documentType?: string | null;

  @Column({ type: 'varchar', length: 50, nullable: true })
  documentNo?: string | null;

  /** YYYY-MM-DD */
  @Column({ type: 'date', nullable: true })
  documentDate?: string | null;

  /** VKN / TCKN of the customer or supplier on the document */
  @Column({ type: 'varchar', length: 20, nullable: true })
  counterpartyTaxId?: string | null;

  @Column({ nullable: true })
  referenceId: string;

  @Column({ nullable: true })
  referenceType: string;

  @Column({ nullable: true })
  note: string;

  /** Display name of the actor (username / apikey:name / SeedSystem) */
  @Column({ nullable: true })
  performedBy: string;

  @Column({ type: 'varchar', length: 36, nullable: true })
  performedByUserId?: string | null;

  @Column({ type: 'varchar', length: 36, nullable: true })
  performedViaApiKeyId?: string | null;

  /** The movement this REVERSAL cancels (each movement can be reversed once). */
  @Index('UQ_stock_movements_reverses', { unique: true })
  @Column({ type: 'varchar', length: 36, nullable: true })
  reversesMovementId?: string | null;

  /** 1, 2, 3, ... per company, without gaps */
  @Column({ type: 'bigint', transformer: { to: (v: number) => v, from: (v: string | number) => (v === null || v === undefined ? v : Number(v)) } })
  sequenceNo: number;

  @Column({ type: 'char', length: 64 })
  prevHash: string;

  @Column({ type: 'char', length: 64 })
  hash: string;

  /** When the row was recorded (DB time, UTC) */
  @Index()
  @CreateDateColumn()
  createdAt: Date;

  /** Response-only: id of the REVERSAL that cancelled this movement */
  reversedByMovementId?: string | null;
}
